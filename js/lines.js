// พี่แฮมเป็นคนพูดเรื่องความดี: คำถามคนดีทุกเกาะ และทั้งเกาะหัวใจ
(function markHam() {
  const mark = s => (typeof s === 'string' && !s.startsWith(HAM) ? HAM + s : s);
  const deeds = o => {
    if (!o || typeof o !== 'object') return;
    for (const k of Object.keys(o)) {
      if (/^deed(Ask|Bad|Good)$/.test(k)) o[k] = mark(o[k]);
      else deeds(o[k]);
    }
  };
  deeds(SAY);
  // ช่องที่เป็นป้ายหรือข้อมูล ไม่ใช่คำพูด
  const notSpoken = new Set(['answer', 'name', 'text', 'icon', 'scene', 'feel', 'bin', 'id']);
  const all = o => {
    for (const k of Object.keys(o)) {
      if (notSpoken.has(k)) continue;
      if (typeof o[k] === 'string') o[k] = mark(o[k]);
      else if (o[k] && typeof o[k] === 'object') all(o[k]);
    }
  };
  all(SAY.heart);
})();

const isHam = text => typeof text === 'string' && text.startsWith(HAM);
// ข้อความที่แสดงบนจอ (ตัดเครื่องหมายผู้พูดออก)
const shown = text => (isHam(text) ? text.slice(HAM.length) : text);

// ข้อความที่ส่งไปอ่านจริง: ตัดอีโมจิ/สัญลักษณ์ และเปลี่ยน เด็กผู้เล่น เป็นคำอ่านไทย
function speakText(text) {
  return shown(text)
    .replace(/[\p{Extended_Pictographic}\u{FE0F}\u{200D}]/gu, '')
    .replace(/["“”➜]/g, '')
    .replace(/\s+/g, ' ').trim();
}

// ชื่อไฟล์เสียงของแต่ละประโยค (FNV-1a) ใช้ทั้งในเกมและในสคริปต์สร้างเสียง
function voiceKey(text) {
  let h = 0x811c9dc5;
  const s = (isHam(text) ? 'ham:' : '') + speakText(text);
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h.toString(16).padStart(8, '0');
}

// รายการประโยคทั้งหมด (ใช้ตอนสร้างไฟล์เสียง)
function allLines() {
  const out = [];
  const walk = v => {
    if (typeof v === 'string') { if (/[฀-๿]/.test(v)) out.push(v); }
    else if (Array.isArray(v)) v.forEach(walk);
    else if (typeof v === 'function') ISLANDS.forEach(i => walk(v(i)));
    else if (v && typeof v === 'object') Object.values(v).forEach(walk);
  };
  walk(SAY);
  return [...new Set(out)];
}
